-- =============================================================================
-- CampusConnect: Location-Aware Campus Resource Reservation System
-- Phase 4 - Physical schema (PostgreSQL)
--
-- Source of truth: database/phase3_schema.dbml (tables, columns, types,
-- NOT NULL, UNIQUE) and phase3_documentation.pdf (referential actions,
-- general constraints).
--
-- Run on a fresh, empty database:
--   psql -v ON_ERROR_STOP=1 -d <test_db> -f database/schema.sql
--
-- Notes
--   * Table names use quoted PascalCase identifiers so PostgreSQL preserves names such as
--     "ImageMetadata" and "User".
--   * Every FK uses ON UPDATE CASCADE (Phase 3 rule I) and an explicit
--     ON DELETE action taken from the Phase 3 referential integrity table.
--   * There are no circular FK references, so tables are created in
--     dependency order with inline constraints:
--       "ImageMetadata" -> "User" -> "Building" -> "ResourceCategory" -> "Resource"
--       -> "ResourceFeature" / "ResourceAvailability" / "MaintenancePeriod"
--       -> "Reservation" -> "CreditTransaction" / "Notification"
--       -> "ReservationReview" / "ResourceReview" / "Session"
--   * The whole script runs in one transaction: it either creates every
--     object or nothing.
-- =============================================================================

BEGIN;

-- -----------------------------------------------------------------------------
-- ImageMetadata: Cloudflare R2 object metadata for profile and resource images.
-- Everything is NOT NULL except alt_text (Phase 3 section 1).
-- -----------------------------------------------------------------------------
CREATE TABLE "ImageMetadata" (
    image_id      integer      GENERATED BY DEFAULT AS IDENTITY,
    object_key    varchar      NOT NULL,
    content_type  varchar      NOT NULL,
    size          bigint       NOT NULL,
    width         integer      NOT NULL,
    height        integer      NOT NULL,
    alt_text      varchar,
    status        varchar      NOT NULL,
    uploaded_at   timestamp    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    filename      varchar      NOT NULL,

    CONSTRAINT pk_imagemetadata            PRIMARY KEY (image_id),
    CONSTRAINT uq_imagemetadata_object_key UNIQUE (object_key)
);

-- -----------------------------------------------------------------------------
-- User
-- -----------------------------------------------------------------------------
CREATE TABLE "User" (
    user_id                 integer       GENERATED BY DEFAULT AS IDENTITY,
    username                varchar       NOT NULL,
    email                   varchar(254)  NOT NULL,
    password_hash           text,
    email_verified_at       timestamp,
    phone_number            varchar(16),
    role                    varchar       NOT NULL DEFAULT 'student',
    created_at              timestamp     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    credit_balance          integer       NOT NULL,
    credit_last_reset       date          NOT NULL,
    is_banned               boolean       NOT NULL,
    can_add_resources       boolean       NOT NULL,
    email_notifications_on  boolean       NOT NULL,
    text_notifications_on   boolean       NOT NULL,
    profile_image_id        integer,

    CONSTRAINT pk_user                  PRIMARY KEY (user_id),
    CONSTRAINT uq_user_username         UNIQUE (username),
    CONSTRAINT uq_user_email            UNIQUE (email),
    CONSTRAINT uq_user_phone_number     UNIQUE (phone_number),
    CONSTRAINT uq_user_profile_image_id UNIQUE (profile_image_id),

    -- Optional 1:0..1 image; the user stays if the image is deleted.
    CONSTRAINT fk_user_profile_image
        FOREIGN KEY (profile_image_id) REFERENCES "ImageMetadata" (image_id)
        ON UPDATE CASCADE ON DELETE SET NULL
);

-- EmailVerificationToken: one-time mailbox-verification tokens.
-- created_at is audit data only; verification does not expire by timestamp.
CREATE TABLE "EmailVerificationToken" (
    token_id    integer    GENERATED BY DEFAULT AS IDENTITY,
    user_id     integer    NOT NULL,
    token_hash  bytea      NOT NULL,
    created_at  timestamp  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    used_at     timestamp,

    CONSTRAINT pk_emailverificationtoken PRIMARY KEY (token_id),
    CONSTRAINT uq_emailverificationtoken_hash UNIQUE (token_hash),
    CONSTRAINT fk_emailverificationtoken_user
        FOREIGN KEY (user_id) REFERENCES "User" (user_id)
        ON UPDATE CASCADE ON DELETE CASCADE
);

CREATE UNIQUE INDEX uq_emailverificationtoken_active_user
    ON "EmailVerificationToken" (user_id)
    WHERE used_at IS NULL;

-- -----------------------------------------------------------------------------
-- Building
-- -----------------------------------------------------------------------------
CREATE TABLE "Building" (
    building_id      integer        GENERATED BY DEFAULT AS IDENTITY,
    building_name    varchar        NOT NULL,
    address          varchar        NOT NULL,
    latitude         decimal(9, 6)  NOT NULL,
    longitude        decimal(9, 6)  NOT NULL,
    google_place_id  varchar,

    CONSTRAINT pk_building                 PRIMARY KEY (building_id),
    CONSTRAINT uq_building_building_name   UNIQUE (building_name),
    CONSTRAINT uq_building_address         UNIQUE (address),
    CONSTRAINT uq_building_google_place_id UNIQUE (google_place_id)
);

-- -----------------------------------------------------------------------------
-- ResourceCategory
-- -----------------------------------------------------------------------------
CREATE TABLE "ResourceCategory" (
    category_id    integer  GENERATED BY DEFAULT AS IDENTITY,
    category_name  varchar  NOT NULL,
    description    text     NOT NULL,

    CONSTRAINT pk_resourcecategory               PRIMARY KEY (category_id),
    CONSTRAINT uq_resourcecategory_category_name UNIQUE (category_name),
    CONSTRAINT uq_resourcecategory_description   UNIQUE (description)
);

-- -----------------------------------------------------------------------------
-- Resource
-- Column "description" corrects the Phase 3 DBML typo "descripton".
-- -----------------------------------------------------------------------------
CREATE TABLE "Resource" (
    resource_id           integer        GENERATED BY DEFAULT AS IDENTITY,
    owner_id              integer        NOT NULL,
    building_id           integer        NOT NULL,
    category_id           integer        NOT NULL,
    name                  varchar        NOT NULL,
    description           text           NOT NULL,
    location_description  text           NOT NULL,
    latitude              decimal(9, 6)  NOT NULL,
    longitude             decimal(9, 6)  NOT NULL,
    max_reservation_time  interval,
    required_credits      integer        NOT NULL,
    capacity              integer        NOT NULL,
    created_at            timestamp      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resource_image_id     integer,

    CONSTRAINT pk_resource                   PRIMARY KEY (resource_id),
    CONSTRAINT uq_resource_resource_image_id UNIQUE (resource_image_id),

    -- An owner with listed resources cannot be deleted; reassign or remove
    -- the resources first.
    CONSTRAINT fk_resource_owner
        FOREIGN KEY (owner_id) REFERENCES "User" (user_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    -- A building that still houses resources cannot be deleted.
    CONSTRAINT fk_resource_building
        FOREIGN KEY (building_id) REFERENCES "Building" (building_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    -- A category that is still in use cannot be deleted.
    CONSTRAINT fk_resource_category
        FOREIGN KEY (category_id) REFERENCES "ResourceCategory" (category_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    -- Optional 1:0..1 image; the resource stays if the image is deleted.
    CONSTRAINT fk_resource_image
        FOREIGN KEY (resource_image_id) REFERENCES "ImageMetadata" (image_id)
        ON UPDATE CASCADE ON DELETE SET NULL
);

-- -----------------------------------------------------------------------------
-- ResourceFeature: meaningless without its resource.
-- -----------------------------------------------------------------------------
CREATE TABLE "ResourceFeature" (
    feature_id    integer  GENERATED BY DEFAULT AS IDENTITY,
    resource_id   integer  NOT NULL,
    feature_name  varchar  NOT NULL,
    description   text     NOT NULL,

    CONSTRAINT pk_resourcefeature PRIMARY KEY (feature_id),

    CONSTRAINT fk_resourcefeature_resource
        FOREIGN KEY (resource_id) REFERENCES "Resource" (resource_id)
        ON UPDATE CASCADE ON DELETE CASCADE
);

-- -----------------------------------------------------------------------------
-- ResourceAvailability: meaningless without its resource.
-- -----------------------------------------------------------------------------
CREATE TABLE "ResourceAvailability" (
    availability_id  integer    GENERATED BY DEFAULT AS IDENTITY,
    resource_id      integer    NOT NULL,
    start_time       timestamp  NOT NULL,
    end_time         timestamp  NOT NULL,
    repeats_until    timestamp,
    repeats_offset   interval,

    CONSTRAINT pk_resourceavailability PRIMARY KEY (availability_id),

    CONSTRAINT fk_resourceavailability_resource
        FOREIGN KEY (resource_id) REFERENCES "Resource" (resource_id)
        ON UPDATE CASCADE ON DELETE CASCADE
);

-- -----------------------------------------------------------------------------
-- MaintenancePeriod: meaningless without its resource.
-- -----------------------------------------------------------------------------
CREATE TABLE "MaintenancePeriod" (
    maintenance_id  integer    GENERATED BY DEFAULT AS IDENTITY,
    resource_id     integer    NOT NULL,
    start_time      timestamp  NOT NULL,
    end_time        timestamp  NOT NULL,
    reason          text       NOT NULL,

    CONSTRAINT pk_maintenanceperiod PRIMARY KEY (maintenance_id),

    CONSTRAINT fk_maintenanceperiod_resource
        FOREIGN KEY (resource_id) REFERENCES "Resource" (resource_id)
        ON UPDATE CASCADE ON DELETE CASCADE
);

-- -----------------------------------------------------------------------------
-- Reservation: historical record; neither parent may be deleted while
-- reservations reference it.
-- -----------------------------------------------------------------------------
CREATE TABLE "Reservation" (
    reservation_id  integer    GENERATED BY DEFAULT AS IDENTITY,
    user_id         integer    NOT NULL,
    resource_id     integer    NOT NULL,
    start_time      timestamp  NOT NULL,
    end_time        timestamp  NOT NULL,
    status          varchar    NOT NULL,
    created_at      timestamp  NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_reservation PRIMARY KEY (reservation_id),

    CONSTRAINT fk_reservation_user
        FOREIGN KEY (user_id) REFERENCES "User" (user_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_reservation_resource
        FOREIGN KEY (resource_id) REFERENCES "Resource" (resource_id)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

-- -----------------------------------------------------------------------------
-- CreditTransaction: financial/audit history; protects the user row.
-- -----------------------------------------------------------------------------
CREATE TABLE "CreditTransaction" (
    transaction_id    integer    GENERATED BY DEFAULT AS IDENTITY,
    user_id           integer    NOT NULL,
    amount            integer    NOT NULL,
    transaction_type  varchar    NOT NULL,
    created_at        timestamp  NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_credittransaction PRIMARY KEY (transaction_id),

    CONSTRAINT fk_credittransaction_user
        FOREIGN KEY (user_id) REFERENCES "User" (user_id)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

-- -----------------------------------------------------------------------------
-- Notification: only meaningful to its recipient.
-- -----------------------------------------------------------------------------
CREATE TABLE "Notification" (
    notification_id    integer    GENERATED BY DEFAULT AS IDENTITY,
    user_id            integer    NOT NULL,
    message            text       NOT NULL,
    notification_type  varchar    NOT NULL,
    created_at         timestamp  NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_notification PRIMARY KEY (notification_id),

    CONSTRAINT fk_notification_user
        FOREIGN KEY (user_id) REFERENCES "User" (user_id)
        ON UPDATE CASCADE ON DELETE CASCADE
);

-- -----------------------------------------------------------------------------
-- ReservationReview: weak entity; PK is also the FK to its reservation
-- (Reservation 1 : 0..1 ReservationReview).
-- -----------------------------------------------------------------------------
CREATE TABLE "ReservationReview" (
    reservation_id       integer    NOT NULL,
    reviewer_user_id     integer    NOT NULL,
    reviewee_user_id     integer    NOT NULL,
    rating               integer    NOT NULL,
    reason               text,
    created_at           timestamp  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    is_anonymous_review  boolean    NOT NULL,

    CONSTRAINT pk_reservationreview PRIMARY KEY (reservation_id),

    -- Phase 3 general constraint: a user cannot review themselves.
    CONSTRAINT ck_reservationreview_reviewer_not_reviewee
        CHECK (reviewer_user_id <> reviewee_user_id),

    CONSTRAINT fk_reservationreview_reservation
        FOREIGN KEY (reservation_id) REFERENCES "Reservation" (reservation_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_reservationreview_reviewer
        FOREIGN KEY (reviewer_user_id) REFERENCES "User" (user_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_reservationreview_reviewee
        FOREIGN KEY (reviewee_user_id) REFERENCES "User" (user_id)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

-- -----------------------------------------------------------------------------
-- ResourceReview
-- -----------------------------------------------------------------------------
CREATE TABLE "ResourceReview" (
    review_id            integer    GENERATED BY DEFAULT AS IDENTITY,
    resource_id          integer    NOT NULL,
    reviewer_user_id     integer    NOT NULL,
    rating               integer    NOT NULL,
    reason               text,
    created_at           timestamp  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    is_anonymous_review  boolean    NOT NULL,

    CONSTRAINT pk_resourcereview PRIMARY KEY (review_id),

    CONSTRAINT fk_resourcereview_resource
        FOREIGN KEY (resource_id) REFERENCES "Resource" (resource_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_resourcereview_reviewer
        FOREIGN KEY (reviewer_user_id) REFERENCES "User" (user_id)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

-- -----------------------------------------------------------------------------
-- Session: login sessions die with their user.
-- -----------------------------------------------------------------------------
CREATE TABLE "Session" (
    session_id  integer    GENERATED BY DEFAULT AS IDENTITY,
    user_id     integer    NOT NULL,
    token_hash  bytea      NOT NULL,
    created_at  timestamp  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at  timestamp  NOT NULL,

    CONSTRAINT pk_session            PRIMARY KEY (session_id),
    CONSTRAINT uq_session_token_hash UNIQUE (token_hash),

    CONSTRAINT fk_session_user
        FOREIGN KEY (user_id) REFERENCES "User" (user_id)
        ON UPDATE CASCADE ON DELETE CASCADE
);

COMMIT;
